'use strict'

const fs = require('node:fs')
const path = require('node:path')

// Keep the standalone SDK independent of engine runtime packages while using
// the exact same public contract. This generated facade contains types only.
const source = path.resolve(__dirname, '../../../internals/schema/api/js/moderation.ts')
const target = path.resolve(__dirname, '../src/server/modules/moderation.ts')
const contract = fs.readFileSync(source, 'utf8')
const expectedImport = "import type { GamePlayer } from './api'"
if (!contract.includes(expectedImport)) throw new Error('Moderation contract import changed; update the SDK type adapter')
const generated = '// Generated by scripts/sync-moderation-types.js. Edit internals/schema/api/js/moderation.ts instead.\n' +
  contract.replace(expectedImport, "import type { GamePlayer } from './player'")
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== generated) fs.writeFileSync(target, generated)
