'use strict'

const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const { execFileSync } = require('node:child_process')
const { validateCatalog } = require('./build-image-downloads')

const services = [
  'player-service',
  'player-auth-portal',
  'server-manager',
  'creator',
  'play',
  'voxa',
]
const common = [
  'package.json',
  'rush.json',
  '.node-version',
  '.dockerignore',
  'docker-compose.yml',
  '.env.docker.example',
  'common/config/rush/',
  'common/scripts/',
  '.github/workflows/package-server.yml',
  'scripts/server-image-plan.js',
  'distribution/LICENSE.txt',
]
const dependencies = {
  'server-manager': [
    'apps/server-manager/',
    'apps/server-manager-rust/',
    'apps/manager-core/',
    'apps/deployment-manager/',
    'internals/apis/',
    'distribution/server/bootstrap.sh',
  ],
  'player-auth-portal': ['apps/player-auth-portal/', 'internals/apis/', 'internals/env/'],
}
const engineDependencies = [
  'apps/local-engine/',
  'apps/game/',
  'apps/voxa/',
  'services/',
  'packages/',
  'internals/',
]

function sourceFingerprint(root, service, files) {
  if (!services.includes(service)) throw new Error('Unknown image service')
  files ||= execFileSync('git', ['ls-files', '-z'], { cwd: root, encoding: 'utf8' })
    .split('\0')
    .filter(Boolean)
  const roots = [...common, ...(dependencies[service] || engineDependencies)]
  const hash = crypto.createHash('sha256').update('box-server-image-cache-v1\0')
  for (const file of files.sort()) {
    if (!roots.some((prefix) => (prefix.endsWith('/') ? file.startsWith(prefix) : file === prefix)))
      continue
    // Committed build outputs are regenerated by the image build.
    if (/(?:^|\/)(?:build|dist|target|node_modules)\//.test(file)) continue
    const absolute = path.join(root, file)
    if (!fs.statSync(absolute, { throwIfNoEntry: false })?.isFile()) continue
    hash.update(file).update('\0').update(fs.readFileSync(absolute)).update('\0')
  }
  return hash.digest('hex')
}

function planImages(root, architecture, catalog, files) {
  const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version
  const imageTag = `v${version}-linux-${architecture}`
  if (catalog) {
    validateCatalog(catalog, architecture)
    if (catalog.imageTag !== imageTag) throw new Error('Cached image catalog version mismatch')
  }
  return services.map((service) => {
    const fingerprint = sourceFingerprint(root, service, files)
    const previous = catalog?.images.find((image) => image.image === `box-local-engine-${service}`)
    return {
      service,
      sourceFingerprint: fingerprint,
      imageTag,
      build:
        !previous || previous.imageTag !== imageTag || previous.sourceFingerprint !== fingerprint,
    }
  })
}

function mergeImages(architecture, catalog, plan, directory) {
  const images = plan.map((item) => {
    const image = item.build
      ? JSON.parse(fs.readFileSync(path.join(directory, `${item.service}.json`), 'utf8')).images[0]
      : catalog.images.find((image) => image.image === `box-local-engine-${item.service}`)
    if (image.image !== `box-local-engine-${item.service}` || image.imageTag !== item.imageTag)
      throw new Error('Built image does not match the requested service and version')
    return { ...image, sourceFingerprint: item.sourceFingerprint }
  })
  return validateCatalog(
    { formatVersion: 2, platform: `linux/${architecture}`, imageTag: plan[0].imageTag, images },
    architecture,
  )
}

if (require.main === module) {
  const [command, architecture, catalogPath, planPath, directory, destination] =
    process.argv.slice(2)
  try {
    if (!['amd64', 'arm64'].includes(architecture)) throw new Error('Unsupported architecture')
    const catalog = fs.existsSync(catalogPath)
      ? JSON.parse(fs.readFileSync(catalogPath, 'utf8'))
      : null
    if (command === 'plan') {
      const plan = planImages(path.resolve(__dirname, '..'), architecture, catalog)
      fs.writeFileSync(planPath, `${JSON.stringify(plan, null, 2)}\n`)
      for (const item of plan)
        console.log(
          `${item.service}: ${item.build ? 'build' : 'reuse verified version/source cache'}`,
        )
    } else if (command === 'merge') {
      const result = mergeImages(
        architecture,
        catalog,
        JSON.parse(fs.readFileSync(planPath, 'utf8')),
        directory,
      )
      fs.writeFileSync(destination, `${JSON.stringify(result, null, 2)}\n`)
    } else throw new Error('Expected plan or merge')
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}

module.exports = { sourceFingerprint, planImages, mergeImages, services }
