'use strict';

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const { validateCatalog } = require('./build-image-downloads');

const services = [
    'player-service',
    'player-auth-portal',
    'server-manager',
    'creator',
    'play',
    'voxa',
];
const common = [
    'package.json',
    'rush.json',
    '.node-version',
    '.dockerignore',
    'docker-compose.yml',
    '.env.docker.example',
    'common/config/rush/',
    'common/scripts/',
    '.github/workflows/package-server.yml',
    'scripts/server-image-plan.js',
    'distribution/LICENSE.txt',
];
const dependencies = {
    'server-manager': [
        'apps/server-manager/',
        'apps/server-manager-rust/',
        'apps/manager-core/',
        'apps/deployment-manager/',
        'internals/apis/',
        'distribution/server/bootstrap.sh',
    ],
    'player-auth-portal': [
        'apps/player-auth-portal/',
        'internals/apis/',
        'internals/env/',
        'packages/deployment-routing/',
    ],
};
const engineDependencies = [
    'apps/local-engine/',
    'apps/game/',
    'apps/voxa/',
    'services/',
    'packages/',
    'internals/',
    'scripts/build-reusable-package.js',
];

function sourceFingerprint(root, service, files) {
    if (!services.includes(service)) {
        throw new Error('Unknown image service');
    }
    files ||= execFileSync('git', ['ls-files', '-z'], { cwd: root, encoding: 'utf8' })
        .split('\0')
        .filter(Boolean);
    const roots = [...common, ...(dependencies[service] || engineDependencies)];
    const hash = crypto.createHash('sha256').update('box-server-image-cache-v1\0');
    for (const file of files.sort()) {
        if (
            !roots.some((prefix) =>
                prefix.endsWith('/') ? file.startsWith(prefix) : file === prefix,
            )
        ) {
            continue;
        }
        // Committed build outputs are regenerated by the image build.
        if (/(?:^|\/)(?:build|dist|target|node_modules)\//.test(file)) {
            continue;
        }
        const absolute = path.join(root, file);
        if (!fs.statSync(absolute, { throwIfNoEntry: false })?.isFile()) {
            continue;
        }
        hash.update(file).update('\0').update(fs.readFileSync(absolute)).update('\0');
    }
    return hash.digest('hex');
}

function planImages(root, architecture, catalog, files) {
    const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
    const releaseTag = `v${version}-linux-${architecture}`;
    if (catalog) {
        validateCatalog(catalog, architecture);
    }
    const forced = new Set(
        String(process.env.BOX_REBUILD_IMAGE_SERVICES || '')
            .split(',')
            .map((value) => value.trim())
            .filter(Boolean),
    );
    return services.map((service) => {
        const fingerprint = sourceFingerprint(root, service, files);
        const previous = catalog?.images.find(
            (image) => image.image === `box-local-engine-${service}`,
        );
        // A release version identifies the package, while an image tag identifies
        // the bytes for one service. Reuse an unchanged service's published tag
        // across package releases so a VOXA-only update does not rebuild or
        // redownload Creator, Play, or the identity services.
        const unchanged =
            previous &&
            !forced.has(service) &&
            (!previous.sourceFingerprint || previous.sourceFingerprint === fingerprint);
        const imageTag = unchanged ? previous.imageTag : releaseTag;
        return {
            service,
            sourceFingerprint: fingerprint,
            imageTag,
            build:
                !previous ||
                forced.has(service) ||
                (!previous.sourceFingerprint ? false : previous.sourceFingerprint !== fingerprint),
        };
    });
}

function mergeImages(architecture, catalog, plan, directory) {
    const images = plan.map((item) => {
        const image = item.build
            ? JSON.parse(fs.readFileSync(path.join(directory, `${item.service}.json`), 'utf8'))
                  .images[0]
            : catalog.images.find((image) => image.image === `box-local-engine-${item.service}`);
        if (
            image.image !== `box-local-engine-${item.service}` ||
            image.imageTag !== item.imageTag
        ) {
            throw new Error('Built image does not match the requested service and version');
        }
        // Reused application images retain release metadata; only freshly built
        // images can claim the current checkout's source fingerprint.
        return item.build ? { ...image, sourceFingerprint: item.sourceFingerprint } : image;
    });
    return validateCatalog(
        {
            formatVersion: 2,
            platform: `linux/${architecture}`,
            // This is the package/release tag. Individual entries may point at
            // older immutable image tags retained from the previous catalog.
            imageTag: `v${JSON.parse(fs.readFileSync(path.join(__dirname, '../package.json'), 'utf8')).version}-linux-${architecture}`,
            images,
        },
        architecture,
    );
}

function planManagerImage(root, architecture, catalog, files) {
    if (!catalog) {
        throw new Error(
            'Published application image catalog is missing. Run the release workflow first.',
        );
    }
    const plan = planImages(root, architecture, catalog, files);
    return plan.map((item) => {
        if (item.service === 'server-manager') {
            const previous = catalog.images.find(
                (image) => image.image === 'box-local-engine-server-manager',
            );
            if (
                !previous.sourceFingerprint &&
                process.env.BOX_REUSE_UNFINGERPRINTED_IMAGES !== 'true'
            ) {
                const version = JSON.parse(
                    fs.readFileSync(path.join(root, 'package.json'), 'utf8'),
                ).version;
                return { ...item, build: true, imageTag: `v${version}-linux-${architecture}` };
            }
            return item;
        }
        const previous = catalog.images.find(
            (image) => image.image === `box-local-engine-${item.service}`,
        );
        return {
            ...item,
            // Application images are published by release.yml and are immutable.
            // Their catalog tag is authoritative even when the package version
            // has advanced.
            imageTag: previous.imageTag,
            build: false,
            sourceFingerprint: previous.sourceFingerprint,
        };
    });
}

if (require.main === module) {
    const [command, architecture, catalogPath, planPath, directory, destination] =
        process.argv.slice(2);
    try {
        if (!['amd64', 'arm64'].includes(architecture)) {
            throw new Error('Unsupported architecture');
        }
        const catalog = fs.existsSync(catalogPath)
            ? JSON.parse(fs.readFileSync(catalogPath, 'utf8'))
            : null;
        if (command === 'plan' || command === 'plan-manager') {
            const planner = command === 'plan-manager' ? planManagerImage : planImages;
            const plan = planner(path.resolve(__dirname, '..'), architecture, catalog);
            fs.writeFileSync(planPath, `${JSON.stringify(plan, null, 2)}\n`);
            for (const item of plan) {
                console.log(
                    `${item.service}: ${item.build ? 'build' : item.service === 'server-manager' ? 'reuse verified version/source cache' : 'reuse published application image'}`,
                );
            }
        } else if (command === 'merge') {
            const result = mergeImages(
                architecture,
                catalog,
                JSON.parse(fs.readFileSync(planPath, 'utf8')),
                directory,
            );
            fs.writeFileSync(destination, `${JSON.stringify(result, null, 2)}\n`);
        } else {
            throw new Error('Expected plan, plan-manager or merge');
        }
    } catch (error) {
        console.error(error.message);
        process.exitCode = 1;
    }
}

module.exports = { sourceFingerprint, planImages, planManagerImage, mergeImages, services };
